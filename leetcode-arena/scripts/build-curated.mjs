/**
 * Build the shipped curated data.
 *
 * Every test is authored as args only. This script runs the trusted Python
 * reference for each case, records the expected JSON value, and fails loudly if
 * a visible example disagrees with the statement. It also emits the reference
 * map used to validate coach-generated tests.
 *
 * Usage: node scripts/build-curated.mjs
 */
import { mkdtempSync, rmSync, writeFileSync, mkdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { spawnSync } from 'node:child_process'
import { PROBLEMS } from './problems.source.mjs'

const here = new URL('.', import.meta.url).pathname
const outFile = join(here, '..', 'data', 'curated.js')

const RUNNER = `import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from solution import Solution
import solution

args = json.load(sys.stdin)
name = sys.argv[1]
instance = Solution()
fn = getattr(instance, name, None)
if fn is None:
    fn = getattr(solution, name)
result = fn(*args)
sys.stdout.write(json.dumps(result))
`

function runReference(dir, name, args) {
  const result = spawnSync('python3', ['-I', '-B', 'runner.py', name], {
    cwd: dir,
    input: JSON.stringify(args),
    encoding: 'utf8',
    timeout: 5000,
    maxBuffer: 8 * 1024 * 1024,
  })
  if (result.error) throw new Error(`reference spawn failed: ${result.error.message}`)
  if (result.status !== 0) {
    throw new Error(`reference failed (${result.status}):\n${result.stderr || result.stdout}`)
  }
  const text = result.stdout.trim()
  try {
    return JSON.parse(text)
  } catch {
    throw new Error(`reference emitted non-JSON: ${text.slice(0, 500)}`)
  }
}

function stable(value) {
  return JSON.stringify(value)
}

const curated = []
const references = {}
let totalVisible = 0
let totalHidden = 0

for (const problem of PROBLEMS) {
  const dir = mkdtempSync(join(tmpdir(), 'lc-build-'))
  try {
    writeFileSync(join(dir, 'solution.py'), problem.reference.python)
    writeFileSync(join(dir, 'runner.py'), RUNNER)
    const name = problem.meta.name

    const fill = (tests, kind) =>
      tests.map((test, index) => {
        if (!Array.isArray(test.args)) throw new Error(`${problem.slug} ${kind}[${index}] is missing args`)
        const expected = runReference(dir, name, test.args)
        return { args: test.args, expected }
      })

    const visible = fill(problem.tests.visible, 'visible')
    const hidden = fill(problem.tests.hidden, 'hidden')

    for (const [index, example] of problem.examples.entries()) {
      const test = visible[index]
      if (!test) throw new Error(`${problem.slug} has more examples than visible tests`)
      let claimed
      try {
        claimed = JSON.parse(example.output)
      } catch {
        throw new Error(`${problem.slug} example ${index + 1} output is not JSON: ${example.output}`)
      }
      if (stable(claimed) !== stable(test.expected)) {
        throw new Error(
          `${problem.slug} example ${index + 1} disagrees with reference:\n  claimed ${stable(claimed)}\n  actual  ${stable(test.expected)}`,
        )
      }
    }

    totalVisible += visible.length
    totalHidden += hidden.length
    references[problem.slug] = problem.reference.python
    const { reference, ...rest } = problem
    curated.push({
      ...rest,
      source: 'curated',
      visibleCount: visible.length,
      hiddenCount: hidden.length,
      tests: { visible, hidden },
    })
    console.log(
      `ok  ${problem.slug.padEnd(48)} visible=${String(visible.length).padStart(2)} hidden=${String(hidden.length).padStart(2)}`,
    )
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

mkdirSync(join(here, '..', 'data'), { recursive: true })
const header = `/**
 * Generated by scripts/build-curated.mjs. Do not edit by hand.
 * ${PROBLEMS.length} curated problems, ${totalVisible} visible and ${totalHidden} hidden cases.
 */
`
writeFileSync(
  outFile,
  `${header}export const CURATED = ${JSON.stringify(curated, null, 2)}\n\nexport const REFERENCES = ${JSON.stringify(references, null, 2)}\n`,
)
console.log(`\nwrote ${outFile}`)
console.log(`${PROBLEMS.length} problems · ${totalVisible} visible · ${totalHidden} hidden`)
